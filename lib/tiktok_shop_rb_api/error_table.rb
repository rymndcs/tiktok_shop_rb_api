    BY_CODE = CODES.flat_map { |klass, codes| codes.map { |code| [code, klass] } }.to_h.freeze

    module_function

    # => the ApiError subclass for this pair; ApiError itself when the code is not documented.
    def classify(code, message)
      code = code.to_s
      message = message.to_s
      rule = MESSAGE_RULES.find { |rule_code, pattern, _| rule_code == code && message.match?(pattern) }
      name = rule ? rule.last : BY_CODE[code]
      name ? TiktokShopRbApi.const_get(name) : ApiError
    end

    # An HTTP-level failure with no TikTok error body. TikTok: "Distinguish 429 from 503"; 503 is not a rate limit.
    # https://partner.tiktokshop.com/docv2/page/rate-limits
    def classify_status(status)
      return RateLimitError if status == 429
      return ServerError if status >= 500

      ApiError
    end
